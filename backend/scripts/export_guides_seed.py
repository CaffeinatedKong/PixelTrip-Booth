"""Generate the destination-guides seed migration from the bundled JSON.

    python backend/scripts/export_guides_seed.py            # rewrite the migration
    python backend/scripts/export_guides_seed.py --check    # exit 1 if it is out of date

``app/agents/data/destination_guides.json`` is the authored source (and the runtime
safety net); the seed migration is derived from it, so the two cannot drift silently:
``--check`` runs in the test suite. Each guide is inserted once (``ON CONFLICT DO
NOTHING``) together with its activities, so re-running the migration on a database whose
guides have since been edited in Supabase changes nothing.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "backend" / "app" / "agents" / "data" / "destination_guides.json"
TARGET = ROOT / "supabase" / "migrations" / "20261014000003_destination_guides_seed.sql"

HEADER = """-- GENERATED by backend/scripts/export_guides_seed.py from
-- backend/app/agents/data/destination_guides.json. Do not edit by hand: change the JSON
-- and regenerate. Each guide is inserted once, with its activities; a guide that already
-- exists (and may have been edited in Supabase) is left exactly as it is.

"""


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def array(values: list[str]) -> str:
    return "ARRAY[" + ", ".join(q(v) for v in values) + "]::TEXT[]" if values else "'{}'::TEXT[]"


def number(value: float) -> str:
    return str(int(value)) if float(value) == int(value) else f"{value:.2f}"


def render() -> str:
    guides = json.loads(SOURCE.read_text(encoding="utf-8"))["guides"]
    blocks = [HEADER]
    for guide in guides:
        rows = []
        for sort_order, act in enumerate(guide["activities"]):
            rows.append(
                "      ("
                + ", ".join(
                    [
                        "gid",
                        str(sort_order),
                        q(act["title"]),
                        q(act["slot"]),
                        q(act["time"]) if act.get("time") else "NULL",
                        q(act["description"]),
                        q(act["location"]),
                        number(act["cost_sgd"]),
                        array(act["tags"]),
                    ]
                )
                + ")"
            )
        blocks.append(
            "\n".join(
                [
                    "DO $$",
                    "DECLARE gid UUID;",
                    "BEGIN",
                    "  INSERT INTO destination_guides",
                    "    (name, keywords, description, details, tags, daily_cost_sgd, typical_days, suggest)",
                    "  VALUES (",
                    f"    {q(guide['name'])}, {array(guide['keywords'])},",
                    f"    {q(guide['description'])},",
                    f"    {q(guide['details'])},",
                    f"    {array(guide['tags'])}, {guide['daily_cost_sgd']}, {guide['typical_days']},"
                    f" {'TRUE' if guide['suggest'] else 'FALSE'})",
                    "  ON CONFLICT (name) DO NOTHING",
                    "  RETURNING id INTO gid;",
                    "  IF gid IS NOT NULL THEN",
                    "    INSERT INTO destination_activities",
                    "      (guide_id, sort_order, title, slot, start_time, description, location, cost_sgd, tags)",
                    "    VALUES",
                    ",\n".join(rows) + ";",
                    "  END IF;",
                    "END $$;",
                    "",
                ]
            )
        )
    return "\n".join(blocks)


def main() -> int:
    sql = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != sql:
            print(f"{TARGET} is out of date; run backend/scripts/export_guides_seed.py")
            return 1
        return 0
    TARGET.write_text(sql, encoding="utf-8")
    print(f"wrote {TARGET} ({sql.count('DO $$')} guides)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
