export function resolveSpriteColor(
  key: string,
  palette: string | null,
): string | null {
  if (key === ".") return null;
  if (key === "c") {
    return (palette && PALETTE_CLOTH_COLOR[palette]) || SPRITE_COLORS.b;
  }
  return SPRITE_COLORS[key] ?? null;
}

export function spriteGridFor(assetKey: string): SpriteGrid | null {
  return SPRITE_GRIDS[assetKey] ?? null;
}
